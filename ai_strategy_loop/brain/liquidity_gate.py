"""Track B 2차 — 거래대금 유동성 게이트 검출 (순수 함수).

R7 실측 근거: refine가 빈도를 올릴 때 LLM이 흑자의 핵심인 거래대금 유동성
게이트(예: 당일거래대금 절대바닥 + 당일거래대금각도 가속 윈도우)를 삭제해
흑자가 깨진다(fullevo3·trackb1 양쪽 확인). 흑자 세대는 이 게이트를 유지,
손실 세대는 통째로 삭제. → 생성된 매수 전략을 저장하기 전에 "거래대금 게이트
포함"을 검증해, 없으면 reject→재생성하게 강제하기 위한 검출기다.

설계:
  - 부작용 없는 순수 함수(단위테스트 가능). 코드 텍스트만 본다.
  - (a) 라인 단위로 `#` 주석을 제거한 뒤,
  - (b) "당일거래대금"을 포함하는 토큰이 같은 줄에서 비교 연산자(<, >, <=, >=)와
        함께 쓰였는지 정규식으로 검사한다.
  - 단순 대입/주석에만 등장하는 경우는 게이트로 보지 않는다(비교 문맥 필수).

R7 ground-truth 교정(false-positive 수정):
  손실 세대(g2/g3)는 '당일거래대금'·'당일거래대금각도'를 전부 삭제하고
  '초당거래대금 / 초당거래대금평균(30) > 3.0' 같은 상대비율 조건만 남긴다.
  이 상대비율은 항상 충족하기 쉬워 유동성 게이트로 불충분하다.
  흑자 게이트 구분자 = **당일거래대금(절대 일누적 유동성 바닥/각도)**의 존재.
  → 검출 토큰을 "거래대금"(모든 계열 포함) → "당일거래대금"으로 좁힌다.
    '당일거래대금각도'는 "당일거래대금" 부분일치로 자연히 포함됨.
    '초당거래대금'/'분당거래대금'은 "당일"이 없어 제외됨.
"""

from __future__ import annotations

import re

# "당일거래대금" 부분일치 → 당일거래대금(절대 바닥) + 당일거래대금각도(가속 윈도우) 검출.
#   의도적 제외: 초당거래대금·분당거래대금(상대비율·항상충족 쉬움 — R7 손실 세대가 남긴 것).
_LIQUIDITY_TOKEN = "당일거래대금"

# 비교 연산자(부등호/범위). `==`/`!=`는 유동성 게이트 의미가 아니므로 제외하고,
#   할당(`=`)·`==` 와 충돌하지 않도록 `<`,`>`,`<=`,`>=` 만 검출한다.
#   (`<=`/`>=`는 `<`/`>` 패턴에 자연히 포함된다.)
_COMPARISON_RE = re.compile(r"[<>]")


def _strip_comments(code: str) -> str:
    """라인 단위로 `#` 이후를 제거한 코드를 반환한다(주석 문맥 배제).

    문자열 리터럴 내부의 `#` 까지 정밀 분리하지는 않지만(1차 검출 목적),
    전략 코드의 거래대금 비교 검출에는 라인 단위 제거로 충분하다.
    """
    out_lines = []
    for line in code.splitlines():
        idx = line.find("#")
        if idx != -1:
            line = line[:idx]
        out_lines.append(line)
    return "\n".join(out_lines)


def has_liquidity_gate(code: str) -> bool:
    """매수 전략 코드에 당일거래대금 유동성 게이트가 비교 조건으로 포함됐는지 검사한다.

    "당일거래대금"을 포함하는 토큰(당일거래대금, 당일거래대금각도 포함)이
    (주석을 제외한) 어떤 줄에서 부등호 비교(`<`, `>`, `<=`, `>=`)와 함께
    1회 이상 등장하면 True.

    초당거래대금·분당거래대금만 있는 코드는 False(상대비율 — R7 손실 세대 패턴).
    단순 대입(`x = 당일거래대금`)이나 주석에만 등장하는 경우도 False.

    Args:
        code: 전략 코드 문자열.

    Returns:
        당일거래대금 비교 게이트가 있으면 True, 없으면 False.
    """
    if not code:
        return False

    stripped = _strip_comments(code)
    for line in stripped.splitlines():
        if _LIQUIDITY_TOKEN not in line:
            continue
        if _COMPARISON_RE.search(line):
            return True
    return False
