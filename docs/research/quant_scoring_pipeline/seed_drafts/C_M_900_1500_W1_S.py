매도 = False

if 등락율 > 29.5:                      # 상한가 직전 청산
    매도 = True
elif 수익률 >= 8.0:                    # 익절(넓게)
    매도 = True
elif 수익률 <= -4.0:                   # 손절(넓게)
    매도 = True
elif 최고수익률 >= 4.0 and 수익률 <= 최고수익률 * 0.6:   # 트레일링(40% 반납 허용)
    매도 = True
elif 보유시간 > 10 and 현재가 < 최저현재가(30, int(보유시간)):   # 10분 후 저점 이탈
    매도 = True
elif 보유시간 > 60 and 수익률 < 1.0:   # 60분 정체 청산
    매도 = True
elif 시분초 >= 150000:                 # 15:00 전량 청산(운영창 종료)
    매도 = True

if 매도:
    self.Sell()
