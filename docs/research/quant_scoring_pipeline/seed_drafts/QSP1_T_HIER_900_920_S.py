매도 = False

if 등락율 > 29.5:                      # 상한가 직전 청산
    매도 = True
elif 수익률 >= 8.0:                    # 익절(넓게)
    매도 = True
elif 수익률 <= -4.0:                   # 손절(넓게)
    매도 = True
elif 최고수익률 >= 4.0 and 수익률 <= 최고수익률 * 0.6:   # 트레일링(40% 반납 허용)
    매도 = True
elif 보유시간 > 300 and 현재가 < 최저현재가(60, int(보유시간)):   # 5분 후 저점 이탈
    매도 = True
elif 보유시간 > 1200 and 수익률 < 1.0:  # 20분 정체 청산
    매도 = True
elif 시분초 >= 92900:                  # 창 종료 직전 전량 청산
    매도 = True

if 매도:
    self.Sell()
